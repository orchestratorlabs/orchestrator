// Covers the Accessibility Report export: one report model rendered to both
// Markdown and PDF, the Markdown format staying exactly as it was, and the PDF's
// page size, text, colors, margins and page-break rules.
import assert from "node:assert/strict";
import { describe, it } from "node:test";
import { buildEvaluationInputs } from "../src/features/orchestrator/doubleCheckReadiness";
import { evaluateButtonAccessibility } from "../src/features/orchestrator/evaluator/buttonEvaluator";
import {
  createObservationState,
  setNote,
  setOutcome,
  type ObservationState,
} from "../src/features/orchestrator/interactionObservations";
import {
  buildAccessibilityReport,
  type BuildReportArgs,
} from "../src/features/orchestrator/report/accessibilityReport";
import { textWidth, toWinAnsi } from "../src/features/orchestrator/report/pdfFonts";
import {
  PAGE_HEIGHT,
  PAGE_WIDTH,
  renderPdf,
  type PdfPage,
} from "../src/features/orchestrator/report/pdfReport";
import { renderMarkdown, type ReportModel } from "../src/features/orchestrator/report/reportModel";
import {
  SAMPLE_BUTTON_CSS,
  SAMPLE_BUTTON_CSS_DARK,
  SAMPLE_BUTTON_TSX,
} from "../src/features/workspace/WorkspacePane";

const lightInputs = buildEvaluationInputs(SAMPLE_BUTTON_TSX, SAMPLE_BUTTON_CSS, "light", SAMPLE_BUTTON_CSS_DARK);
const darkInputs = buildEvaluationInputs(SAMPLE_BUTTON_TSX, SAMPLE_BUTTON_CSS, "dark", SAMPLE_BUTTON_CSS_DARK);
const lightResult = evaluateButtonAccessibility(lightInputs.reactCode, lightInputs.effectiveCss);
const darkResult = evaluateButtonAccessibility(darkInputs.reactCode, darkInputs.effectiveCss);

const NOW = new Date(2026, 10, 6, 14, 9);

function observed(): ObservationState {
  let state = createObservationState();
  state = setOutcome(state, "focus", "no-issue", NOW);
  state = setNote(state, "focus", "Focus stayed on the button.", NOW);
  state = setOutcome(state, "announcement", "problem", NOW);
  state = setNote(
    state,
    "announcement",
    "VoiceOver read 'Save changes, button.' I heard no completion announcement.",
    NOW
  );
  return state;
}

function args(overrides: Partial<BuildReportArgs> = {}): BuildReportArgs {
  return {
    componentName: "Button",
    reviewerLabel: "John Doe · Developer (demo placeholder)",
    approval: { at: "11/06/2026 at 2:12 PM", theme: "light", findingTotal: lightResult.findings.length },
    generatedAt: "11/06/2026 at 2:15 PM",
    lightResult,
    darkResult,
    lightResultInputs: lightInputs,
    darkResultInputs: darkInputs,
    currentInputsByTheme: { light: lightInputs, dark: darkInputs },
    observations: observed(),
    ...overrides,
  };
}

// ── helpers to read the PDF back without a PDF library ───────────────────────

function pdfText(bytes: Uint8Array): string {
  return new TextDecoder("latin1").decode(bytes);
}

/** Every `(text) Tj` string in the file, with PDF string escapes undone. */
function shownStrings(bytes: Uint8Array): string[] {
  const out: string[] = [];
  const re = /\(((?:\\.|[^\\)])*)\) Tj/g;
  const raw = pdfText(bytes);
  for (let m = re.exec(raw); m; m = re.exec(raw)) {
    out.push(
      m[1].replace(/\\([0-7]{3})/g, (_, o) => String.fromCharCode(parseInt(o, 8))).replace(/\\(.)/g, "$1")
    );
  }
  return out;
}

const pageLines = (page: PdfPage) => page.lines.map((l) => l.text);
const squash = (s: string) => s.replace(/\s+/g, " ").trim();

describe("one report model, two renderers", () => {
  it("renders the Markdown export in the existing format", () => {
    const md = renderMarkdown(buildAccessibilityReport(args()).blocks);
    const lines = md.split("\n");
    assert.equal(lines[0], "# OrchestratoR Accessibility Report");
    assert.equal(lines[1], "");
    assert.equal(lines[2], "Component: Button");
    assert.equal(lines[3], "Approved by John Doe · Developer (demo placeholder) · 11/06/2026 at 2:12 PM");
    assert.equal(
      lines[4],
      `Approved scope: Light mode · all ${lightResult.findings.length} evaluated findings`
    );
    assert.equal(lines[5], "Report generated: 11/06/2026 at 2:15 PM");
    assert.equal(lines[6], "");
    assert.equal(lines[7], "## Light mode — Approved result");
    assert.equal(lines[8], "");
    assert.match(lines[9], /^CSS source: /);
    assert.match(lines[10], /^Score: 85\/100 \(\d+ pass, \d+ unknown, \d+ fail/);
    assert.equal(lines[11], "");
    assert.equal(lines[12], "### Findings");
    assert.match(lines[13], /^1\. \[(Fail|Unknown|Pass|N\/A)\] /);
    assert.match(md, /\n {3}Recommendation: /);
    assert.match(md, /\n### Recommended fixes\n- /);
    assert.match(md, /\n## Dark mode — Not covered by this approval\n/);
    assert.match(md, /\n## Interaction observations \(manual, simulated\)\n\nSource: /);
    assert.ok(md.endsWith("\n---\nGenerated by OrchestratoR"));
  });

  it("still names an unevaluated theme exactly as before", () => {
    const md = renderMarkdown(
      buildAccessibilityReport(args({ darkResult: null, darkResultInputs: null })).blocks
    );
    assert.match(
      md,
      /\n## Dark mode\n\nNot yet evaluated — switch to dark mode and run the accessibility check to include it\.\n/
    );
  });

  it("puts the reviewer's outcomes, notes and timestamps in both formats", () => {
    const model = buildAccessibilityReport(args());
    const md = renderMarkdown(model.blocks);
    const pdf = shownStrings(renderPdf(model, { now: NOW }).bytes).join("\n");
    for (const needle of [
      "Keyboard focus after activation",
      "Status: No issue observed",
      "Focus stayed on the button.",
      "Screen-reader announcement after saving",
      "Status: Problem observed",
      "I heard no completion announcement.",
      "Outcome recorded by John Doe",
      "Approved scope: Light mode",
    ]) {
      assert.ok(md.includes(needle), `markdown is missing: ${needle}`);
      assert.ok(squash(pdf).includes(squash(needle)), `pdf is missing: ${needle}`);
    }
  });

  it("carries the reviewer's actual entries, not fixed text", () => {
    let state = setOutcome(createObservationState(), "focus", "problem", NOW);
    state = setNote(state, "focus", "Focus jumped to the page header.", NOW);
    const model = buildAccessibilityReport(args({ observations: state }));
    const md = renderMarkdown(model.blocks);
    const pdf = squash(shownStrings(renderPdf(model, { now: NOW }).bytes).join(" "));
    assert.ok(md.includes("Status: Problem observed"));
    assert.ok(md.includes("Focus jumped to the page header."));
    assert.ok(pdf.includes("Focus jumped to the page header."));
    assert.ok(!pdf.includes("I heard no completion announcement"));
    assert.ok(!md.includes("I heard no completion announcement"));
    // The untouched check stays Untested in both.
    assert.ok(pdf.includes("Status: Untested"));
  });
});

describe("PDF file structure", () => {
  const model = buildAccessibilityReport(args());
  const rendered = renderPdf(model, { now: NOW });
  const raw = pdfText(rendered.bytes);

  it("is a PDF on US Letter (612 × 792 pt)", () => {
    assert.ok(raw.startsWith("%PDF-1.4\n"));
    assert.ok(raw.trimEnd().endsWith("%%EOF"));
    assert.equal(PAGE_WIDTH, 612);
    assert.equal(PAGE_HEIGHT, 792);
    const boxes = raw.match(/\/MediaBox \[0 0 612 792\]/g) ?? [];
    assert.equal(boxes.length, rendered.pages.length);
    assert.match(raw, /\/Type \/Pages [^>]*\/Count \d+/);
  });

  it("has a valid cross-reference table", () => {
    const start = Number(raw.match(/startxref\n(\d+)\n%%EOF/)![1]);
    assert.equal(raw.slice(start, start + 4), "xref");
    const entries = [...raw.slice(start).matchAll(/^(\d{10}) 00000 n $/gm)].map((m) => Number(m[1]));
    assert.ok(entries.length >= 6);
    entries.forEach((offset, i) => {
      assert.ok(raw.slice(offset).startsWith(`${i + 1} 0 obj`), `object ${i + 1} is at its offset`);
    });
    const declared = Number(raw.match(/\/Size (\d+)/)![1]);
    assert.equal(declared, entries.length + 1);
  });

  it("declares /Length correctly for every content stream", () => {
    for (const m of raw.matchAll(/<< \/Length (\d+) >>\nstream\n([\s\S]*?)\nendstream/g)) {
      assert.equal(m[2].length, Number(m[1]));
    }
  });

  it("uses real text operators in standard fonts, so the text is selectable", () => {
    assert.match(raw, /\/BaseFont \/Helvetica /);
    assert.match(raw, /\/BaseFont \/Helvetica-Bold /);
    assert.ok(shownStrings(rendered.bytes).length > 40);
    assert.ok(!/\/Subtype \/Image/.test(raw), "no page is a picture of text");
  });

  it("draws a white page with black body text and gray secondary text", () => {
    assert.match(raw, /1 1 1 rg\n0 0 612 792 re\nf/);
    assert.match(raw, /0 0 0 rg [\d.]+ [\d.]+ Td/); // black
    assert.match(raw, /0\.35 0\.35 0\.35 rg [\d.]+ [\d.]+ Td/); // gray
  });

  it("titles the document and sets its language", () => {
    assert.match(raw, /\/Title \(OrchestratoR Accessibility Report\)/);
    assert.match(raw, /\/Lang \(en-US\)/);
  });

  it("keeps every line inside the page margins", () => {
    for (const page of rendered.pages) {
      for (const l of page.lines) {
        assert.ok(l.x >= 54, `left margin: ${l.text}`);
        assert.ok(l.x + textWidth(l.text, l.font, l.size) <= PAGE_WIDTH - 54 + 0.5, `right margin: ${l.text}`);
        assert.ok(l.top + l.leading <= PAGE_HEIGHT - 66 + 0.5, `bottom margin: ${l.text}`);
        assert.ok(l.top >= 54, `top margin: ${l.text}`);
      }
    }
  });
});

describe("PDF page breaks", () => {
  /** A long report: many findings, and notes long enough to span several lines. */
  function longModel(noteLines: number): ReportModel {
    const long = Array.from({ length: noteLines }, (_, i) => `line ${i + 1} of the note`).join("\n");
    let state = setOutcome(createObservationState(), "focus", "no-issue", NOW);
    state = setNote(state, "focus", long, NOW);
    state = setOutcome(state, "announcement", "problem", NOW);
    state = setNote(state, "announcement", `${long}\nI heard no completion announcement.`, NOW);
    return buildAccessibilityReport(args({ observations: state }));
  }

  const pageOf = (pages: PdfPage[], text: string) =>
    pages.findIndex((p) => pageLines(p).some((l) => l.includes(text)));

  it("keeps each outcome with its note and attribution on one page, wherever the break falls", () => {
    // Sweeping the note length moves the page break through the observations section.
    // Stops at 40 lines: a check taller than one page cannot be kept together (it is
    // split line by line, covered below).
    for (let n = 1; n <= 40; n += 1) {
      const { pages } = renderPdf(longModel(n), { now: NOW });
      const focus = pageOf(pages, "Status: No issue observed");
      const focusNote = pageOf(pages, "line 1 of the note");
      const focusStamp = pageOf(pages, "Outcome recorded by");
      assert.equal(focus, focusNote, `focus outcome and note on one page (note length ${n})`);
      assert.equal(focus, focusStamp, `focus outcome and stamp on one page (note length ${n})`);

      const ann = pageOf(pages, "Status: Problem observed");
      const annNote = pageOf(pages, "I heard no completion announcement.");
      assert.equal(ann, annNote, `announcement outcome and note on one page (note length ${n})`);
      const annTitle = pageOf(pages, "Screen-reader announcement after saving");
      assert.equal(ann, annTitle, `announcement title with its outcome (note length ${n})`);
    }
  });

  it("actually breaks pages in that sweep (so the check above is not vacuous)", () => {
    const { pages } = renderPdf(longModel(60), { now: NOW });
    assert.ok(pages.length >= 3);
    const headings = pages.map((p) => pageOf([p], "Interaction observations"));
    assert.ok(headings.some((i) => i >= 0));
  });

  it("never leaves a heading as the last line on a page", () => {
    for (let n = 1; n <= 70; n += 1) {
      const { pages } = renderPdf(longModel(n), { now: NOW });
      for (const page of pages) {
        const last = page.lines[page.lines.length - 1];
        assert.ok(
          !(last.font === "bold" && last.size >= 11),
          `heading stranded at page foot: "${last.text}" (note length ${n})`
        );
      }
    }
  });

  it("never starts a page with a recommendation, so a finding is not split from it", () => {
    const { pages } = renderPdf(buildAccessibilityReport(args()), { now: NOW });
    assert.ok(pages.length >= 2, "the report spans pages, so this checks something");
    for (const page of pages) {
      assert.ok(!page.lines[0].text.startsWith("Recommendation:"), page.lines[0].text);
    }
  });

  it("still lays out a note taller than a page, line by line", () => {
    const { pages } = renderPdf(longModel(120), { now: NOW });
    assert.ok(pageOf(pages, "line 120 of the note") >= 0);
  });
});

describe("PDF text encoding", () => {
  it("keeps accented letters, curly quotes, dashes and the middle dot", () => {
    const { text, replaced } = toWinAnsi("Café — “quoted” · it’s … fine");
    assert.equal(replaced, 0);
    assert.equal(text.length, "Café — “quoted” · it’s … fine".length);
  });

  it("keeps line breaks in a note instead of running the lines together", () => {
    assert.equal(toWinAnsi("one\r\ntwo\nthree").text, "one\ntwo\nthree");
    const state = setNote(createObservationState(), "focus", "first line\nsecond line", NOW);
    const rendered = renderPdf(buildAccessibilityReport(args({ observations: state })), { now: NOW });
    const shown = shownStrings(rendered.bytes);
    assert.ok(shown.some((t) => t.includes("first line")));
    assert.ok(shown.includes("second line"), "second line starts its own line");
  });

  it("replaces what the font cannot hold and counts it, so nothing is lost silently", () => {
    const { text, replaced } = toWinAnsi("ok 日本 ✨");
    assert.equal(replaced, 3);
    assert.equal(text, "ok ?? ?");
  });

  it("says so in the PDF when a note contained characters it could not show", () => {
    const state = setNote(createObservationState(), "announcement", "Heard 日本語", NOW);
    const model = buildAccessibilityReport(args({ observations: state }));
    const rendered = renderPdf(model, { now: NOW });
    assert.equal(rendered.replacedCharacters, 3);
    const text = squash(shownStrings(rendered.bytes).join(" "));
    assert.match(text, /3 characters in this report could not be shown in the PDF/);
    assert.match(text, /Markdown export keeps the original text/);
  });

  it("adds no notice when nothing was replaced", () => {
    const rendered = renderPdf(buildAccessibilityReport(args()), { now: NOW });
    assert.equal(rendered.replacedCharacters, 0);
    assert.ok(!squash(shownStrings(rendered.bytes).join(" ")).includes("could not be shown"));
  });

  it("escapes parentheses and backslashes in text", () => {
    const state = setNote(createObservationState(), "focus", "Focus (kept) on C:\\btn", NOW);
    const rendered = renderPdf(buildAccessibilityReport(args({ observations: state })), { now: NOW });
    assert.ok(shownStrings(rendered.bytes).some((s) => s.includes("Focus (kept) on C:\\btn")));
  });

  it("has a width for every printable ASCII character in both fonts", () => {
    for (let c = 32; c <= 126; c += 1) {
      const ch = String.fromCharCode(c);
      assert.ok(textWidth(ch, "regular", 1000) > 0, `regular ${ch}`);
      assert.ok(textWidth(ch, "bold", 1000) > 0, `bold ${ch}`);
    }
    assert.equal(textWidth("i", "regular", 1000), 222);
    assert.equal(textWidth("W", "bold", 1000), 944);
    assert.equal(textWidth("~", "regular", 1000), 584);
  });
});
